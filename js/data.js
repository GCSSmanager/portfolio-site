function splitImages(folder, count) {
  const paths = Array.from({ length: count }, (_, i) => `data/${folder}/${i + 1}.webp`);
  const mid = Math.ceil(paths.length / 2);
  return {
    column1: paths.slice(0, mid),
    column2: paths.slice(mid)
  };
}

